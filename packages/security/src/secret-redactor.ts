/**
 * Redacts secrets, tokens, credentials, and keys from logs, outputs, and database persistence.
 */
export class SecretRedactor {
  public static redact(text: string): string {
    if (!text || typeof text !== 'string') return text;

    let sanitized = text;

    // 0. PEM Private Keys (RSA, EC, OPENSSH, DSA, and generic private keys, single or multiline)
    sanitized = sanitized.replace(
      /-----BEGIN\s+([A-Z0-9_-]+\s+)?PRIVATE\s+KEY-----[\s\S]*?-----END\s+([A-Z0-9_-]+\s+)?PRIVATE\s+KEY-----/gi,
      '[REDACTED_PRIVATE_KEY]'
    );

    // 1. Telegram Bot Token (e.g., 123456789:ABCdefGhIJKlmNoPQRsTUVwxyZ)
    sanitized = sanitized.replace(/\b\d{8,11}:[A-Za-z0-9_-]{30,50}\b/g, '[REDACTED_TELEGRAM_TOKEN]');

    // 2. Gemini API Key (starts with AIza...)
    sanitized = sanitized.replace(/\bAIza[0-9A-Za-z-_]{30,45}\b/g, '[REDACTED_GEMINI_KEY]');

    // 3. Groq API Key (starts with gsk_...)
    sanitized = sanitized.replace(/\bgsk_[a-zA-Z0-9]{20,}\b/g, '[REDACTED_GROQ_KEY]');

    // 4. OpenRouter / OpenAI Key (starts with sk-...)
    sanitized = sanitized.replace(/\bsk-[a-zA-Z0-9_-]{20,}\b/g, '[REDACTED_AI_KEY]');

    // 5. GitHub Tokens (starts with ghp_, gho_, ghu_, etc.)
    sanitized = sanitized.replace(/\bgh[pousr]_[A-Za-z0-9_]{20,}\b/g, '[REDACTED_GITHUB_TOKEN]');

    // 6. Google OAuth Access / Refresh Tokens (ya29....)
    sanitized = sanitized.replace(/\bya29\.[0-9A-Za-z-_]+\b/g, '[REDACTED_OAUTH_TOKEN]');

    // 7. Database connection URLs with passwords (postgres://, mysql://, etc.)
    sanitized = sanitized.replace(
      /\b(postgres|postgresql|mysql|mongodb|redis):\/\/([^:\s]+):([^@\s]+)@([^\s]+)\b/gi,
      '$1://$2:[REDACTED_DB_PASSWORD]@$4'
    );

    // 8. Generic HTTP/HTTPS/FTP URLs with embedded credentials (e.g. https://user:pass@host/path)
    sanitized = sanitized.replace(
      /\b(https?|ftp):\/\/([^/\s]+:[^/\s]+)@([^\s"'`<>]+)/gi,
      '$1://[REDACTED_CREDENTIALS]@$3'
    );

    // 8. Device Secret Hex Tokens (64-character hex strings generated by pairing)
    sanitized = sanitized.replace(/\b[a-f0-9]{64}\b/gi, '[REDACTED_DEVICE_SECRET]');

    // 9. Cloudflare API Tokens (40 alphanumeric / underscore / dash characters)
    // Avoid matching common words by requiring mixed case/digits or specific token boundaries
    sanitized = sanitized.replace(/\b[a-zA-Z0-9_-]{40}\b/g, (match) => {
      // Only redact if string contains both letters and numbers/symbols (high entropy token)
      if (/[0-9]/.test(match) && /[a-zA-Z]/.test(match)) {
        return '[REDACTED_CLOUDFLARE_TOKEN]';
      }
      return match;
    });

    // 10. Bearer authorization headers
    sanitized = sanitized.replace(/Bearer\s+([A-Za-z0-9\-._~+/]{8,})/gi, 'Bearer [REDACTED_AUTH_TOKEN]');

    return sanitized;
  }
}
